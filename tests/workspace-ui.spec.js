import { test, expect } from '@playwright/test';
import { createGame, validateSave } from '../src/game.js';

test('command context follows its workspace without disclosing uncontacted civilizations or changing the campaign', async ({ page }) => {
  const state = createGame('workspace-context');
  state.factions[0].contacts = ['veyr', 'khar'];
  state.factions.find(f => f.id === 'veyr').contacts.push('player');
  state.factions.find(f => f.id === 'khar').contacts.push('player');
  expect(validateSave(state)).toBe(true);
  const errors = [], artRequests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (request.url().includes('/art/')) artRequests.push(request.url()); });
  await page.addInitScript(saved => localStorage.setItem('asterion-reach-save-v1', JSON.stringify(saved)), state);
  await page.goto('./');
  const before = await page.evaluate(() => window.__asterion.getState());
  expect(artRequests).toEqual([]);
  await page.locator('[data-page="diplomacy"]').click();
  await expect(page.locator('#inspector h2')).toHaveText('Veyr Consortium');
  await page.locator('[data-illustration="veyr"] img').evaluate(img => img.decode());
  await expect(page.locator('[data-rival="choir"]')).not.toContainText('Luminous');
  await expect(page.locator('[data-rival="choir"] [data-action="rival-dossier"]')).toHaveCount(0);
  await page.locator('[data-rival="khar"] [data-action="rival-dossier"]').click();
  await expect(page.locator('#inspector h2')).toHaveText('Khar Dominion');
  await page.locator('[data-illustration="khar"] img').evaluate(img => img.decode());
  await page.locator('[data-action="rival-channel"]').click();
  await expect(page.locator('[data-rival="khar"] .rival-actions button:not(:disabled)').first()).toBeFocused();
  expect(artRequests.every(url => /(?:veyr-consortium|khar-dominion)\.webp$/.test(url))).toBe(true);
  await page.locator('[data-page="research"]').click();
  expect(await page.locator('#workspace-page').evaluate(element=>element.scrollTop)).toBe(0);
  await expect(page.locator('#workspace-page h2')).toBeInViewport();
  await expect(page.locator('#inspector h2')).toHaveText('Your archives');
  await page.locator('#inspector [data-action="inspect"]').first().click();
  await expect(page.locator('.inspector')).toHaveAttribute('aria-label', 'System inspector');
  await expect(page.locator('#inspector h2')).toHaveText('Solace');
  await page.locator('[data-page="empire"]').click();
  await expect(page.locator('#inspector h2')).toHaveText('The working empire');
  await page.locator('[data-page="journal"]').click();
  await expect(page.locator('#inspector h2')).toHaveText('Stories of the Reach');
  expect(await page.evaluate(() => window.__asterion.getState())).toEqual(before);
  expect(errors).toEqual([]);
});
