test('future snapshots stay deeply immutable through repair, renaming, new research and JSON replay', () => {
  const scenario = fixture(game), { state, attacker } = scenario;
  const report = attack(scenario).combatReports[0], saved = clone(report);
  assert.ok(Object.isFrozen(report.rounds) && Object.isFrozen(report.rounds[0]) && Object.isFrozen(report.rounds[0].attacker));
  assert.throws(() => { report.rounds[0].attacker.rawHit = 0; }, TypeError);
  assert.throws(() => { report.rounds.push({}); }, TypeError);
  assert.equal(game.command(state, { type: 'repair', fleetId: attacker.id }).ok, true);
  attacker.name = 'Renamed after the engagement';
  assert.equal(game.command(state, { type: 'research', techId: 'weapons' }).ok, true);
  empire(state).science = 70;
  const restored = clone(state);
  game.endTurn(state); game.endTurn(restored);
  assert.deepEqual(clone(state), restored);
  assert.ok(empire(state).techs.includes('weapons'));
  assert.deepEqual(report, saved);
  assert.deepEqual(state.combatReports.find(item => item.id === report.id), saved);
  assert.equal(game.validateSave(restored), true);
});

