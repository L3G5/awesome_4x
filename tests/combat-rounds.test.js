test('malformed, unbounded, discontinuous or arithmetically inconsistent traces are rejected', () => {
  const scenario = fixture(game); attack(scenario);
  const changes = [
    report => { report.rounds = null; },
    report => { report.rounds = []; },
    report => { report.rounds.push(clone(report.rounds[3])); },
    report => { report.rounds[0].number = 0; },
    report => { report.rounds[0].attacker = null; },
    report => { report.rounds[0].hiddenFleetId = 'f999'; },
    report => { report.rounds[0].attacker.extra = 1; },
    report => { delete report.rounds[0].attacker.firepower; },
    report => { report.rounds[0].attacker.rawHit = Infinity; },
    report => { report.rounds[0].attacker.rawHit = -1; },
    report => { report.rounds[0].attacker.rawHit = report.rounds[0].attacker.firepower * 1.15; },
    report => { report.rounds[0].attacker.firepower++; },
    report => { report.rounds[0].attacker.weaponsFactor = 1.5; },
    report => { report.rounds[0].attacker.factionFactor = 1.15; },
    report => { report.rounds[0].defender.shieldFactor = .6; },
    report => { report.rounds[1].attacker.shieldFactor = 1; },
    report => { report.rounds[0].attacker.shipsBefore = 13; },
    report => { report.rounds[0].attacker.shipsAfter = .5; },
    report => { report.rounds[0].attacker.hullBefore--; },
    report => { report.rounds[1].attacker.hullBefore--; },
    report => { report.rounds[3].defender.hullAfter--; },
    report => { report.rounds.pop(); },
  ];
  for (const [index, change] of changes.entries()) {
    const invalid = clone(scenario.state); change(invalid.combatReports[0]);
    assert.equal(game.validateSave(invalid), false, `trace mutation ${index}`);
  }
  const killed = fixture(game, { aShips: 1, dShips: 1, aHull: 1, dHull: 1 }); attack(killed);
  const afterDeath = clone(killed.state), report = afterDeath.combatReports[0];
  report.rounds.push({ ...clone(report.rounds[0]), number: 2 });
  assert.equal(game.validateSave(afterDeath), false, 'no second round after mutual destruction');
});

test('report retention bounds round storage to fifty reports and two hundred exchanges', () => {
  const scenario = fixture(game); attack(scenario);
  const restored = clone(scenario.state), source = restored.combatReports[0];
  restored.combatReports = Array.from({ length: 50 }, (_, index) => ({ ...clone(source), id: index + 1 }));
  restored.nextCombatReportId = 51;
  assert.equal(restored.combatReports.reduce((count, report) => count + report.rounds.length, 0), 200);
  assert.equal(game.validateSave(restored), true);
  restored.combatReports.push({ ...clone(source), id: 51 }); restored.nextCombatReportId = 52;
  assert.equal(game.validateSave(restored), false);
});
