test('all thirteen ordinary command and complete next-cycle outcomes match the archived pre-trace engine', () => {
  for (const expected of baseline) {
    const scenario = fixture(game, expected.options), { state } = scenario;
    assert.equal(hash(state), expected.initial, `${expected.options.name}: exact initial state`);
    const result = attack(scenario);
    assert.equal(result.ok, true);
    assert.equal(hash(withoutRounds(result)), expected.result, `${expected.options.name}: complete command result`);
    assert.equal(hash(withoutRounds(state)), expected.state, `${expected.options.name}: complete post-command state`);
    assert.equal(state.rng, expected.rng);
    assert.equal(game.validateSave(state), true);
    const next = game.endTurn(state);
    assert.equal(hash(withoutRounds(next)), expected.nextResult, `${expected.options.name}: complete endTurn result`);
    assert.equal(hash(withoutRounds(state)), expected.nextState, `${expected.options.name}: complete next-cycle state`);
    assert.equal(game.validateSave(state), true);
  }
});

